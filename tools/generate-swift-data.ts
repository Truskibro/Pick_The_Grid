/**
 * Generates the Swift data files for the native iOS app from the Expo
 * TypeScript constants (single source of truth for series data).
 *
 * Run from the project root:  bun tools/generate-swift-data.ts
 * Writes:
 *   ios-pick-the-grid-ios/PickTheGridIOS/SeriesData.swift   (F1 + MotoGP constants)
 *   ios-pick-the-grid-ios/PickTheGridIOS/SeedData.swift     (seed users + predictions)
 */
import { TEAMS, DRIVERS, RACES } from "../expo/constants/f1-data";
import {
  MOTOGP_TEAMS,
  MOTOGP_RIDERS,
  MOTOGP_RACES,
  MOTOGP_RACE_RESULTS,
} from "../expo/constants/motogp-data";
import { SEED_USERS, SEED_PREDICTIONS } from "../expo/constants/seed-predictions";

const swStr = (s: string | undefined | null) =>
  s == null ? "nil" : JSON.stringify(s);

const swTeam = (t: any) =>
  `  Team(id: ${swStr(t.id)}, name: ${swStr(t.name)}, color: ${swStr(t.color)}, shortName: ${swStr(t.shortName)})`;

const swDriver = (d: any) =>
  `  Driver(id: ${swStr(d.id)}, name: ${swStr(d.name)}, shortName: ${swStr(d.shortName)}, number: ${d.number ?? 0}, teamId: ${swStr(d.teamId)}, championshipPoints: ${d.championshipPoints ?? 0})`;

const swRace = (r: any) =>
  `  Race(id: ${swStr(r.id)}, round: ${r.round ?? 0}, name: ${swStr(r.name)}, location: ${swStr(r.location)}, country: ${swStr(r.country)}, countryFlag: ${swStr(r.countryFlag)}, raceDate: ${swStr(r.raceDate)}, raceTime: ${swStr(r.raceTime)}, status: ${swStr(r.status ?? "upcoming")}!, hasSprint: ${!!r.hasSprint}, sprintDate: ${swStr(r.sprintDate)}, sprintTime: ${swStr(r.sprintTime)}, winner: ${swStr(r.winner)}, currentLap: ${r.currentLap ?? "nil"}, totalLaps: ${r.totalLaps ?? "nil"}, seriesId: ${swStr(r.seriesId ?? "f1")})`;

const swEntry = (e: any) =>
  `      ClassificationEntry(position: ${e.position}, driverId: ${swStr(e.driverId)}, time: ${swStr(e.time ?? "")}, gap: ${swStr(e.gap ?? "")}, points: ${e.points ?? 0}, status: ${swStr(e.status ?? "finished")}!)`;

const swResult = (r: any) => {
  const cls = r.classification.map(swEntry).join(",\n");
  const spr = (r.sprintClassification ?? []).map(swEntry).join(",\n");
  const dnf = (r.dnfDriverIds ?? []).map((d: string) => JSON.stringify(d)).join(", ");
  const dns = (r.dnsDriverIds ?? []).map((d: string) => JSON.stringify(d)).join(", ");
  return `  RaceResult(raceId: ${swStr(r.raceId)}, classification: [\n${cls}\n  ], fastestLapDriverId: ${swStr(r.fastestLapDriverId)}, dnfDriverIds: [${dnf}], dnsDriverIds: [${dns}], sprintClassification: ${spr ? `[\n${spr}\n  ]` : "nil"})`;
};

const seriesData = `//
//  SeriesData.swift
//  Generated by tools/generate-swift-data.ts from the Expo TS constants.
//  Do not edit by hand — rerun the generator instead.
//

import Foundation

// ── F1 fallback data (used when Supabase is unreachable or empty) ──────────

let F1_FALLBACK_TEAMS: [Team] = [
${TEAMS.map(swTeam).join(",\n")}
]

let F1_FALLBACK_DRIVERS: [Driver] = [
${DRIVERS.map(swDriver).join(",\n")}
]

let F1_FALLBACK_RACES: [Race] = [
${RACES.map(swRace).join(",\n")}
]

// ── MotoGP data (bundled — the Expo app ships these as local constants) ────

let MOTOGP_TEAMS_DATA: [Team] = [
${MOTOGP_TEAMS.map(swTeam).join(",\n")}
]

let MOTOGP_RIDERS_DATA: [Driver] = [
${MOTOGP_RIDERS.map(swDriver).join(",\n")}
]

let MOTOGP_RACES_DATA: [Race] = [
${MOTOGP_RACES.map(swRace).join(",\n")}
]

let MOTOGP_RACE_RESULTS_DATA: [RaceResult] = [
${MOTOGP_RACE_RESULTS.map(swResult).join(",\n")}
]
`;

const swSeedPred = (raceId: string, p: any) =>
  `      ${JSON.stringify(raceId)}: SeedPrediction(raceId: ${swStr(p.raceId)}, top10: [${(p.top10 ?? []).map((d: string) => JSON.stringify(d)).join(", ")}], fastestLap: ${swStr(p.fastestLap)}, dnf: ${swStr(p.dnf)}, sprintTop8: [${(p.sprintTop8 ?? []).map((d: string) => JSON.stringify(d)).join(", ")}])`;

const userEntries = Object.entries(SEED_PREDICTIONS).map(([uid, preds]) => {
  const inner = Object.entries(preds as Record<string, any>)
    .map(([rid, p]) => swSeedPred(rid, p))
    .join(",\n");
  return `    ${JSON.stringify(uid.toLowerCase())}: [\n${inner}\n    ]`;
});

const seedData = `//
//  SeedData.swift
//  Generated by tools/generate-swift-data.ts from the Expo TS constants.
//  Do not edit by hand — rerun the generator instead.
//

import Foundation

struct SeedUser {
  let userId: String
  let username: String
  let displayName: String
}

struct SeedPrediction {
  let raceId: String
  let top10: [String]
  let fastestLap: String?
  let dnf: String?
  let sprintTop8: [String]
}

let SEED_USERS_DATA: [SeedUser] = [
${SEED_USERS.map((u) => `  SeedUser(userId: ${swStr(u.userId)}, username: ${swStr(u.username)}, displayName: ${swStr(u.displayName)})`).join(",\n")}
]

let SEED_PREDICTIONS_DATA: [String: [String: SeedPrediction]] = [
${userEntries.join(",\n")}
]
`;

import { writeFileSync, mkdirSync } from "fs";
const dir = new URL("../ios-pick-the-grid-ios/PickTheGridIOS/", import.meta.url).pathname;
mkdirSync(dir, { recursive: true });
writeFileSync(dir + "SeriesData.swift", seriesData);
writeFileSync(dir + "SeedData.swift", seedData);
console.log("Wrote SeriesData.swift and SeedData.swift");
